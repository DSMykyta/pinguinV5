const test = require('node:test');
const assert = require('node:assert/strict');
test('nutrition QA and ingredient highlights', async () => {
 const { analyzeTable, ingredientMatches } = await import('../js/generators/generator-table/gt-nutrition-checks.js');
const r=(left,right)=>({left,right});
const table=(basis,rows,ingredients)=>[r('Харчова цінність',basis),...rows,{separator:true},{left:'Інгредієнти',header:true,single:true},{left:ingredients,single:true}];
const labels=(rows,i)=>analyzeTable(rows).hints[i].map(h=>h.label);
const check=(rows,i,label)=>assert.ok(labels(rows,i).includes(label),JSON.stringify({rows,i,label,actual:labels(rows,i)}));
const fusion=table('50 г',[r('Калорії','165 ккал'),r('Жири','5.4 г'),r('Вуглеводи','13.5 г'),r('- цукор','10.5 г'),r('- поліоли','5 г'),r('Харчові волокна','10 г'),r('Білок','12.5 г'),r('Сіль','0.12 г')],'рисові кульки (рис, декстроза), соєвий білок, мальтитол');
check(fusion,3,'Carb Error');check(fusion,6,'High Fiber');check(fusion,7,'High Protein');check(fusion,7,'25%');check(fusion,8,'Low Salt');
assert.ok(!labels(fusion,4).includes('No Added Sugar'));
for(const label of ['Added Sugar','Sweeteners','Allergens'])assert.ok(analyzeTable(fusion).highlights.at(-1).left.some(x=>x.label===label));
assert.deepEqual(labels(table('50 г',[r('цукор','0.25 г')],'мальтитол'),1),['Sugar Free']);
check(table('50 г',[r('цукор','2 г')],'декстроза'),1,'Low Sugar');
check(table('100 мл',[r('цукор','2.5 г')],'декстроза'),1,'Low Sugar');
assert.ok(!labels(table('100 мл',[r('цукор','3 г')],'декстроза'),1).includes('Low Sugar'));
check(table('50 г',[r('цукор','10 г')],'сушене манго'),1,'No Added Sugar');
check(table('50 г',[r('цукор','1 г')],''),3,'Missing Ingredients');
check(table('50 г',[r('Жири','0.25 г')],''),1,'Fat Free');
check(table('100 мл',[r('Жири','1.5 г')],''),1,'Low Fat');
check(table('100 г',[r('Сіль','0.0125 г')],''),1,'Salt Free');
check(table('100 г',[r('Сіль','0.1 г')],''),1,'Very Low Salt');
check(table('100 мл',[r('Калорії','4 ккал')],''),1,'Calorie Free');
check(table('100 г',[r('Калорії','40 ккал')],''),1,'Low Calorie');
check(table('100 г',[r('Калорії','200 ккал'),r('Білок','6 г')],''),2,'Source of Protein');
check(table('100 г',[r('Калорії','100 ккал'),r('Харчові волокна','3 г')],''),2,'High Fiber');
check(table('50 г',[r('Жири','40 г'),r('Білок','20 г')],''),0,'Mass Error');
check(table('50 г',[r('Жири','2 г'),r('- насичені','3 г')],''),1,'Fat Error');
check(table('50 г',[r('Вуглеводи','2 г'),r('- цукор','3 г')],''),2,'Sugar Error');
check(table('50 г',[r('Жири','2 г'),r('Жири','3 г')],''),2,'Duplicate');
check(table('50 г',[r('Жири','2 мл')],''),1,'Unit Check');
check(table('50 г',[r('Білок','')],''),1,'Missing Value');
check(table('50 г',[r('Калорії','300 ккал'),r('Жири','1 г'),r('Вуглеводи','1 г'),r('Білок','1 г')],''),1,'Calorie Check');
check(table('50 г',[r('поліоли','6 г')],''),1,'Polyol Warning');
assert.deepEqual(labels([r('Вітамін C','80 мг')],0),['100% NRV']);
assert.deepEqual(labels([r('Вітамін D','5 мкг')],0),['100% NRV']);
assert.deepEqual(labels([r('Лейцин','2 г')],0),['BCAA']);
assert.deepEqual(labels([r('Лізин','2 г')],0),['EAA']);
assert.deepEqual(labels([r('EPA','200 мг')],0),['EPA']);
assert.deepEqual(labels([r('Магній (елементарний)','100 мг')],0),['27% NRV','Elemental']);
assert.ok(ingredientMatches('аспартам, кофеїн, молоко').some(x=>x.label==='Aspartame'));
assert.ok(ingredientMatches('аспартам, кофеїн, молоко').some(x=>x.label==='Caffeine'));
assert.ok(!ingredientMatches('кокосове молоко').some(x=>x.label==='Allergens'));
assert.ok(!ingredientMatches('ізомальтоолігосахариди').length);

});
